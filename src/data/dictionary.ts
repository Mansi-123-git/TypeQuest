export function getWordOfTheDay(words: DictionaryWord[] = STARTER_DICTIONARY): DictionaryWord {
  const now = new Date();
  const dayIndex =
    now.getFullYear() * 366 + now.getMonth() * 31 + now.getDate();
  return words[dayIndex % words.length];
}
